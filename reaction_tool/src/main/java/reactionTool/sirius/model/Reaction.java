package reactionTool.sirius.model;

public class Reaction {
    private String name;
    private String smarts;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSmarts() {
        return smarts;
    }

    public void setSmarts(String smarts) {
        this.smarts = smarts;
    }
}
